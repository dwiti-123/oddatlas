import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
const js=ts.transpileModule(fs.readFileSync('lib/adventure-wall.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(js,{exports});
const {parseWall,wallPoint,emptyWall,limit}=exports;
const valid={id:'test',kind:'note',art:0,message:'A little story',signature:'A traveller',place:'Hashima',x:45,y:55,angle:2};
assert.equal(parseWall('{broken'),emptyWall);
assert.equal(parseWall(JSON.stringify({traces:{},votes:[]})),emptyWall);
let wall=parseWall(JSON.stringify({traces:[valid,valid,{...valid,id:'bad',kind:'script'},{...valid,id:'coords',x:null}],votes:['test','test',null,23]}));
assert.equal(wall.traces.length,1);
assert.equal(wall.votes.length,1);
wall=parseWall(JSON.stringify({traces:[{...valid,message:'x'.repeat(300),signature:'y'.repeat(100),x:-50,y:300,angle:80}],votes:[]}));
assert.equal(wall.traces[0].message.length,120);assert.equal(wall.traces[0].signature.length,28);
assert.equal(wall.traces[0].x,wallPoint(-50,300).x);assert.equal(wall.traces[0].y,wallPoint(-50,300).y);assert.equal(wall.traces[0].angle,5);
assert.equal(parseWall(JSON.stringify({traces:Array.from({length:40},(_,i)=>({...valid,id:'t'+i})),votes:[]})).traces.length,limit);
const roundTrip=parseWall(JSON.stringify({traces:[valid],votes:['test']}));
assert.equal(roundTrip.traces[0].message,valid.message);assert.equal(roundTrip.votes[0],'test');
console.log('Adventure wall: malformed data, duplicate IDs/votes, bounds, text limits, capacity and persistence round trip passed.');
